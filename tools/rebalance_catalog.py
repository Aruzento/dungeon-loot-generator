def base_name_for(roll: int, index: int, current_name: str) -> str:
    if roll in LOW_BASE_OVERRIDES and index in LOW_BASE_OVERRIDES[roll]:
        return LOW_BASE_OVERRIDES[roll][index]
    if roll == 18:
        return ROLL18_BASE_NAMES[index]
    if roll == 19:
        return ROLL19_BASE_NAMES[index]
    return current_name


def band_tag(roll: int) -> str:
    if roll <= 10:
        return "household"
    if roll <= 15:
        return "equipment"
    return {
        16: "transition-magic",
        17: "good-magic",
        18: "strong-magic",
        19: "very-rare",
        20: "exceptional",
    }[roll]


def base_metadata(
    roll: int,
    index: int,
    name: str,
    tag: str,
    normal_detail: str,
    lucky_detail: str,
    lucky_suffix: str,
) -> tuple[str, str, str, str]:
    if roll <= 10:
        tag = LOW_TAG_REPLACEMENTS.get(tag, tag)
        normal_detail = LOW_BASE_DETAILS.get(index, normal_detail)
        suffix, effect = LOW_LUCKY.get(tag, LOW_LUCKY["oddity"])
        return (
            tag,
            normal_detail,
            f"{name} — {suffix}",
            f"{effect} Малое свойство относится именно к находке «{name}».",
        )
    return tag, normal_detail, f"{name} — {lucky_suffix}", lucky_detail


def extra_profile_for(roll: int):
    if roll <= 10:
        return LOW_EXTRA_PROFILE
    if roll <= 15:
        return GEAR_EXTRA_PROFILE
    return MAGIC_EXTRA_PROFILE


def roll20_metadata(index: int, name: str) -> tuple[str, str, str, str]:
    tag, detail = ROLL20_GROUPS[index // 25]
    description = f"Находка «{name}» {detail}."
    lucky_name = f"{name} — с подтверждённой безупречной атрибуцией"
    lucky_description = (
        f"Полная экспертиза подтверждает исключительное происхождение находки «{name}» и повышает её коллекционную цену. "
        "В игре эта версия не используется: lucky-двадцатка сразу обращается к отдельному пулу артефактов."
    )
    return tag, description, lucky_name, lucky_description
