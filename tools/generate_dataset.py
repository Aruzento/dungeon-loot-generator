def main() -> None:
    if set(ROLL_NAMES) != set(range(1, 20)):
        missing = sorted(set(range(1, 20)) - set(ROLL_NAMES))
        raise SystemExit(f"Missing roll catalogs: {missing}")
    if len(SLOTS) != 55 or len(LUCKY_SUFFIXES) != 55:
        raise SystemExit("Slot metadata must contain exactly 55 entries")
    for roll, names in ROLL_NAMES.items():
        if len(names) != 55:
            raise SystemExit(f"Roll {roll} contains {len(names)} names instead of 55")

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    item_path = DATA_DIR / "items.csv"
    with item_path.open("w", encoding="utf-8-sig", newline="") as handle:
        fieldnames = [
            "id", "roll", "name", "description", "value_cp", "lucky_name",
            "lucky_description", "lucky_value_cp", "tags",
        ]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        record_id = 1
        for roll in range(1, 20):
            for index, (name, slot) in enumerate(zip(ROLL_NAMES[roll], SLOTS)):
                tag, normal_detail, lucky_detail = slot
                value = item_value(roll, index)
                writer.writerow(
                    {
                        "id": f"I{record_id:04d}",
                        "roll": roll,
                        "name": name,
                        "description": f"{CONDITIONS[roll]} {normal_detail}",
                        "value_cp": value,
                        "lucky_name": f"{name} — {LUCKY_SUFFIXES[index]}",
                        "lucky_description": f"{lucky_detail} {LUCKY_TIERS[roll]} {LUCKY_ENDINGS[(roll * 3 + index) % len(LUCKY_ENDINGS)]}",
                        "lucky_value_cp": value * lucky_multiplier(roll, index),
                        "tags": f"{tag},tier-{roll}",
                    }
                )
                record_id += 1

    artifact_path = DATA_DIR / "artifacts.csv"
    with artifact_path.open("w", encoding="utf-8-sig", newline="") as handle:
        fieldnames = ["id", "roll", "name", "official_name", "description", "value_cp", "polarity", "source", "tags"]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for artifact in ARTIFACTS:
            row = dict(zip(("id", "name", "official_name", "description", "value_cp", "polarity", "source", "tags"), artifact))
            writer.writerow({"roll": 20, **row})

    print(f"Wrote {record_id - 1} regular items to {item_path}")
    print(f"Wrote {len(ARTIFACTS)} artifacts to {artifact_path}")


if __name__ == "__main__":
    main()
